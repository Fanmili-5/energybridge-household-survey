"""Frozen reference construction choices, with regional design provenance.

All physical values are generated by the same pinned complete public builder.
Targets select named full source options; unknown regional facts stay unknown.
This module does not supply a measured home or a code-compliance certificate.
"""
import copy

from .common import ROOT, read, require
from .reference_workflow import ref
from .source_adapter import source_file

CATALOG = 'configs/regional_enclosure_packages_v1.json'


def package(country, site_id=None, *, root=ROOT):
    catalog = read(root / CATALOG)
    matches = [v for v in catalog['packages'] if v['country'] == country]
    require(len(matches) == 1, 'REGIONAL_REFERENCE_PACKAGE_UNKNOWN', country)
    item = matches[0]; value = read(source_file(item['package'], root))
    require(value['schema'] == 'national_idf.regional_reference_enclosure_package.v1'
            and value['country'] == country, 'REGIONAL_REFERENCE_PACKAGE_SCHEMA')
    require(site_id is None or site_id in value['declared_reference_sites'], 'REGIONAL_REFERENCE_SITE_OUTSIDE_PACKAGE', site_id)
    for evidence in value['sources'].values(): source_file(evidence, root)
    require(value['representation'] == 'controlled_reference'
            and not value['measured_home_or_stock_claimed'] and not value['code_compliance_claimed'],
            'REGIONAL_REFERENCE_SCOPE_REQUIRED')
    return value, item['package']


def apply(country, site_id, arguments, *, root=ROOT):
    import csv
    value, binding = package(country, site_id, root=root)
    result = copy.deepcopy(arguments)
    for key, option in value['builder_enclosure_overrides'].items():
        require(key.startswith('enclosure_'), 'REGIONAL_REFERENCE_NONENCLOSURE_OVERRIDE', key)
        source = source_file(value['option_files'][key], root)
        with source.open() as stream: names = {v['Option Name'] for v in csv.DictReader(stream, delimiter='\t')}
        require(option in names, 'REGIONAL_REFERENCE_NOT_PUBLIC_OPTION', [key, option])
        result[key] = option
    return result, {'package': binding, 'id': value['id'], 'country': country,
                    'reference_targets': value['design_targets'], 'representation': value['representation'],
                    'post_recipe_id': value.get('post_recipe_id'),
                    'facts_or_demand_inputs_modified': False}


def audit(fixture, country, site_id, *, root=ROOT):
    """Independent static readback of the actual complete native construction.

    Ordinary exterior surfaces are distinguished from the builder's small
    window/door support buffers. Ground U is deliberately not inferred here.
    """
    from .idf import Fields, objects, parse
    from .reference_enclosure import proxy_faces, polygon_area
    from .envelope_adaptation import construction_properties
    value, binding = package(country, site_id, root=root)
    rows = parse(source_file(fixture['model'], root).read_text())
    fields = Fields(source_file(fixture['engine_schema'], root)); proxies = proxy_faces(rows, fields, root=root)
    targets = value['design_targets']; faces = {}; checks = {}; measurements = []
    for index, row in enumerate(rows):
        if row[0] != 'BuildingSurface:Detailed': continue
        faces[row[1]] = row
        role = fields.get(row, 'surface_type'); boundary = fields.get(row, 'outside_boundary_condition')
        if index in proxies or boundary != 'Outdoors' or role not in ('Wall', 'Roof'): continue
        construction = next(r for r in objects(rows, 'Construction') if r[1] == fields.get(row, 'construction_name'))
        properties = construction_properties(rows, construction, fields)
        films = value['static_design_films_m2K_W'][role]
        measurements.append({'role': role, 'surface': row[1], 'area_m2': polygon_area(row, fields),
                             'R_layers_m2K_W': properties['R_layers_m2K_W'],
                             'C_layers_J_m2K': properties['C_layers_J_m2K'],
                             'reference_static_U_W_m2K': 1 / (properties['R_layers_m2K_W'] + films),
                             'reference_films_m2K_W': films})
    for role in ('Wall', 'Roof'):
        members = [v for v in measurements if v['role'] == role]
        limit = targets.get(role + '_U_max_W_m2K'); minimum = targets.get(role + '_R_min_m2K_W')
        if members and (limit is not None or minimum is not None):
            mean_U = sum(v['area_m2'] * v['reference_static_U_W_m2K'] for v in members) / sum(v['area_m2'] for v in members)
            checks[role] = {'area_weighted_static_U_W_m2K': mean_U, 'target_U_max_W_m2K': limit,
                            'target_R_min_m2K_W': minimum,
                            'passed': mean_U <= limit if limit is not None else 1 / mean_U >= minimum}
    windows = []; doors = []
    for row in objects(rows, 'FenestrationSurface:Detailed'):
        parent = faces[fields.get(row, 'building_surface_name')]
        if fields.get(parent, 'outside_boundary_condition') != 'Outdoors': continue
        kind = fields.get(row, 'surface_type')
        if kind not in ('Window', 'Door'): continue
        construction = next(r for r in objects(rows, 'Construction') if r[1] == fields.get(row, 'construction_name'))
        if kind == 'Door':
            properties = construction_properties(rows, construction, fields)
            doors.append({'surface': row[1], 'area_m2': polygon_area(row, fields),
                          'U_W_m2K': 1 / (properties['R_layers_m2K_W'] + value['static_design_films_m2K_W']['Wall'])})
            continue
        layers = [r for r in rows if r[0].startswith('WindowMaterial:') and r[1] in construction[2:]]
        require(len(layers) == 1 and layers[0][0] == 'WindowMaterial:SimpleGlazingSystem', 'REGIONAL_WINDOW_READBACK_MODEL_UNSUPPORTED')
        windows.append({'surface': row[1], 'area_m2': polygon_area(row, fields), 'U_W_m2K': float(layers[0][2]), 'SHGC': float(layers[0][3])})
    maximum = targets.get('Window_U_max_W_m2K')
    if maximum is not None:
        checks['Window'] = {'target_U_max_W_m2K': maximum, 'passed': all(v['U_W_m2K'] <= maximum for v in windows)}
    if country == 'IN':
        walls = [v for v in measurements if v['role'] == 'Wall']
        total_area = sum(v['area_m2'] for v in walls + windows + doors)
        opaque_term = sum(v['area_m2'] * v['reference_static_U_W_m2K'] for v in walls) + sum(v['area_m2'] * v['U_W_m2K'] for v in doors)
        window_term = sum(v['area_m2'] * v['U_W_m2K'] for v in windows)
        solar_term = sum(v['area_m2'] * v['SHGC'] for v in windows)
        bound = 1.156 * (5.15 * opaque_term + 1.31 * window_term + 65.21 * solar_term) / total_area
        checks['ENS2018_reference_RETV_upper_bound'] = {'W_m2': bound, 'limit_W_m2': 15,
             'max_orientation_factor': 1.156, 'source': 'ENS2018 Eq4 Table3 Annex6 Table9',
             'no_shading_credit_taken': True, 'actual_door_and_window_area_included': True, 'passed': bound <= 15}
    require(all(v['passed'] for v in checks.values()), 'REGIONAL_NATIVE_DESIGN_TARGET_FAILED', checks)
    return {'package': binding, 'measurements': measurements, 'windows': windows, 'doors': doors,
            'target_checks': checks, 'all_declared_static_targets_passed': True,
            'ground_and_adjacent_floor_not_assessed_as_plane_U': True,
            'not_exposed_roles': [r for r in ('Wall', 'Roof') if not any(v['role'] == r for v in measurements)],
            'not_current_code_compliance_or_stock_equivalence': True,
            'regional_constraints_not_supplied_remain_null': targets,
            'complete_reference_models_generated_by_pinned_public_algorithm': True}
